// scaffold is a test helper that calls CatalogScaffold with OutputFile set to
// a temp file so tests never touch the working directory. It returns the
// rendered YAML string so assertions can be made without reading the file.
func scaffold(t *testing.T, opts generate.CatalogScaffoldOptions) string {
	t.Helper()
	opts.OutputFile = filepath.Join(t.TempDir(), "catalog.yaml")
	out, err := generate.CatalogScaffold(opts)
	if err != nil {
		t.Fatalf("CatalogScaffold: unexpected error: %v", err)
	}
	return out
}

// scaffoldErr calls CatalogScaffold and asserts that it returns an error
// containing the given substring.
func scaffoldErr(t *testing.T, opts generate.CatalogScaffoldOptions, wantErrContains string) {
	t.Helper()
	opts.OutputFile = filepath.Join(t.TempDir(), "catalog.yaml")
	_, err := generate.CatalogScaffold(opts)
	if err == nil {
		t.Fatalf("CatalogScaffold: expected error containing %q, got nil", wantErrContains)
	}
	if !strings.Contains(err.Error(), wantErrContains) {
		t.Fatalf("error %q does not contain %q", err.Error(), wantErrContains)
	}
}

// assertContains fails the test if sub is not found in s.
func assertContains(t *testing.T, s, sub, label string) {
	t.Helper()
	if !strings.Contains(s, sub) {
		t.Errorf("%s: expected output to contain %q\n\nFull output:\n%s", label, sub, s)
	}
}

// assertAbsent fails the test if sub is found in s.
func assertAbsent(t *testing.T, s, sub, label string) {
	t.Helper()
	if strings.Contains(s, sub) {
		t.Errorf("%s: expected output NOT to contain %q\n\nFull output:\n%s", label, sub, s)
	}
}

// ── Mode tests ────────────────────────────────────────────────────────────────

func TestCatalogScaffold_DynamicDefault(t *testing.T) {
	out := scaffold(t, generate.CatalogScaffoldOptions{})

	// Header and apiVersion must be present.
	assertContains(t, out, `Generated by "inrun generate catalog"`, "header")
	assertContains(t, out, "apiVersion: inrun.dev/v1", "apiVersion")
	assertContains(t, out, "kind: Catalog", "kind")

	// Dynamic mode: default: true, no mode: typed.
	assertContains(t, out, "default: true", "default")
	assertAbsent(t, out, "mode: typed", "no typed mode")

	// Dynamic mode includes the declarative template comments.
	assertContains(t, out, "# onCreate:", "dynamic onCreate comment")
	assertContains(t, out, "# onReconcile:", "dynamic onReconcile comment")

	// Dynamic mode must NOT contain the hooks, constructor, or typed-only apiTypes fields.
	assertAbsent(t, out, "# hooks:", "no hooks in dynamic mode")
	assertAbsent(t, out, "# constructor:", "no constructor in dynamic mode")
	assertAbsent(t, out, "object: TODO", "no object field in dynamic mode")
	assertAbsent(t, out, "objectList: TODO", "no objectList field in dynamic mode")

	// workers must be correctly indented (6 spaces, same level as resync).
	assertContains(t, out, "      workers:", "workers at correct indent")
}

