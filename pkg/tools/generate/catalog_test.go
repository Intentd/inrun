// ── Output structure ──────────────────────────────────────────────────────────

func TestCatalogScaffold_AlwaysHasRequiredFields(t *testing.T) {
	// Every variant must produce a complete Catalog skeleton.
	cases := []generate.CatalogScaffoldOptions{
		{},
		{AddHook: true},
		{AddConstructor: true},
		{Typed: true},
	}
	required := []string{
		"apiVersion: inrun.dev/v1",
		"kind: Catalog",
		"metadata:",
		"spec:",
		"crds:",
		"apiTypes:",
		"workers:",
		"resync:",
		"operatorBox:",
	}
	for _, opts := range cases {
		out := scaffold(t, opts)
		for _, field := range required {
			assertContains(t, out, field, "required field in "+flagSuffix(opts))
		}
	}
}

func flagSuffix(o generate.CatalogScaffoldOptions) string {
	switch {
	case o.AddHook:
		return "--add-hook"
	case o.AddConstructor:
		return "--add-constructor"
	case o.Typed:
		return "--typed"
	default:
		return "dynamic"
	}
}

// ── Validate unit tests ───────────────────────────────────────────────────────

func TestValidate_Valid(t *testing.T) {
	cases := []generate.CatalogScaffoldOptions{
		{},
		{AddHook: true},
		{AddConstructor: true},
		{Typed: true},
		{AddHook: true, AddSecurity: true},
	}
	for _, c := range cases {
		if err := c.Validate(); err != nil {
			t.Errorf("Validate(%+v): unexpected error: %v", c, err)
		}
	}
}

func TestValidate_Invalid(t *testing.T) {
	cases := []struct {
		opts    generate.CatalogScaffoldOptions
		wantErr string
	}{
		{generate.CatalogScaffoldOptions{AddHook: true, AddConstructor: true}, "mutually exclusive"},
		{generate.CatalogScaffoldOptions{AddHook: true, Typed: true}, "mutually exclusive"},
		{generate.CatalogScaffoldOptions{AddConstructor: true, Typed: true}, "mutually exclusive"},
		{generate.CatalogScaffoldOptions{AddHook: true, AddConstructor: true, Typed: true}, "mutually exclusive"},
	}
	for _, c := range cases {
		err := c.opts.Validate()
		if err == nil {
			t.Errorf("Validate(%+v): expected error containing %q, got nil", c.opts, c.wantErr)
			continue
		}
		if !strings.Contains(err.Error(), c.wantErr) {
			t.Errorf("Validate(%+v): error %q does not contain %q", c.opts, err.Error(), c.wantErr)
		}
	}
}
